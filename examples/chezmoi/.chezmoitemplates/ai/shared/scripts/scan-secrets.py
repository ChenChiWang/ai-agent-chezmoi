def wrapper(path):
    opening, closing = '{' * 2, '}' * 2
    def include(p, trim=True):
        name = p[len('.chezmoitemplates/'):]
        return (opening + ' template "' + name + '" . ' + ('-' if trim else '') + closing + '\n').encode()
    if path in ('dot_claude/CLAUDE.md.tmpl', 'dot_codex/AGENTS.md.tmpl'):
        product = 'claude' if path.startswith('dot_claude/') else 'codex'
        return BANNER + include(PREFIX + 'shared/instructions.md', False) + include(PREFIX + 'adapters/' + product + '.md')
    skill = skill_of(path, SKILL_SOURCES[1:])
    if skill:
        return include(SKILL_ROOT + skill_names([skill])[-1] + '/SKILL.md')
    if path == 'dot_claude/skills/dotfiles-sync/executable_sync.sh.tmpl':
        return include(PREFIX + 'shared/scripts/legacy-sync.sh')
    for script in SCRIPTS:
        if path == 'dot_config/ai-agent/bin/' + ('' if script.endswith('.json') else 'executable_') + script + '.tmpl':
            return include(PREFIX + 'shared/scripts/' + script)
    raise ValueError('unknown wrapper')


OPEN = b'{' * 2
LITERAL_OPEN = OPEN + b' "' + OPEN + b'" ' + b'}' * 2


def encode_shared(content):
    """Represent arbitrary literal UTF-8 text using only a static opener escape."""
    return content.replace(OPEN, LITERAL_OPEN)


def decode_shared(content):
    parts = content.split(LITERAL_OPEN)
    if any(OPEN in part for part in parts):
        raise ValueError('unsupported dynamic template')
    return OPEN.join(parts)



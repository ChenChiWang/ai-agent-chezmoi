def admitted(location):
    """LOCATIONS plus the per-skill paths of any validly named skill, which no fixed list can hold."""
    if location in LOCATIONS:
        return True
    scope, _, path = location.partition('/')
    kinds = (SKILL_SOURCES + SKILL_LEGACY if scope in ('source', 'index', 'head')
             else SKILL_TARGETS if scope in ('target', 'render') else ())
    name = skill_of(path, kinds)
    try:
        return bool(name) and name in skill_names([name])
    except ValueError:
        return False


# These deployment namespaces are reserved even in a staged Claude-only profile.
# Checking their lexical relationship does not inspect inactive product files.
TARGET_REGIONS = ('.claude', '.codex', '.agents', '.config/ai-agent')

# 機器本地參數檔的封閉欄位集合。它提供路徑與身分，不提供任何寫入或發布授權。
AGENTS = ('claude', 'codex')
CONFIG_KEYS = dict(source='path', destination='path', plan_dir='path', scanner='path',
                   profile='profile', repository_profile='profile', writer='agent',
                   remote='text', branch='text', author_name='text', author_email='text',
                   auto_in='bool')


def load_config(path):
    """Machine-local sync parameters: owner-controlled, closed key set, no secrets."""
    p = Path(path)
    if not p.is_absolute() or is_redirected(p):
        raise ValueError('config path')
    info = p.stat()
    if not stat.S_ISREG(info.st_mode) or info.st_size > 65536:
        raise ValueError('config file')
    if not private_file(p, info):
        # Windows 說明是哪個主體讓它不私有（只有 SID 與權限遮罩）；POSIX 的訊息不變
        raise ValueError('config file' + (': owner=%s aces=%s user=%s token_owner=%s' % (
            *security_descriptor(p), current_user_sid(), token_owner_sid()) if WINDOWS else ''))
    doc = read_json(p)
    if type(doc) is not dict or not set(doc) <= set(CONFIG_KEYS):
        raise ValueError('config keys')
    for key, value in doc.items():
        kind = CONFIG_KEYS[key]
        if kind == 'bool':
            ok = type(value) is bool
        elif kind == 'agent':
            # writer：單一 agent、agent 清單、"any"（不檢查）或 "none"（agent 一律不可發布）。
            ok = ((type(value) is str and value in AGENTS + ('any', 'none'))
                  or (type(value) is list and 0 < len(value) <= len(AGENTS) and len(set(value)) == len(value)
                      and all(type(v) is str and v in AGENTS for v in value)))
        else:
            ok = type(value) is str and 0 < len(value) <= 4096 and not any(ord(c) < 32 for c in value)
            if ok and kind == 'path':
                ok = absolute_path(value)
            elif ok and kind == 'profile':
                ok = value in PROFILES
        if not ok:
            raise ValueError('config value')
    return doc


def overlaps(left, right):
    return left == right or left in right.parents or right in left.parents


def validate_layout(source, destination, profile, legacy=False, source_profile=None):
    """Validate roots and only managed paths; never enumerate destination.

    The managed paths are the fixed ones plus those of the source's own skills,
    found by listing three fixed source directories (source_skills).

    Explicit root aliases (including macOS /tmp) are canonicalized. Within those
    roots, symlink components, non-directory parents and hard-linked payloads
    are refused. Source may be below destination only outside target namespaces.
    """
    src, dst = Path(source).resolve(), Path(destination).resolve()
    if not src.is_dir() or not dst.is_dir() or src == dst or src in dst.parents:
        raise ValueError('invalid roots')
    # All engines allocate scratch state beneath this fixed OS temporary root.
    # A selected root must not encompass that allocation area (e.g. HOME=/tmp).
    if scratch_conflict(src, dst, temporary_root().resolve()):
        raise ValueError('root contains engine scratch area')
    if any(overlaps(src, dst / region) for region in TARGET_REGIONS):
        raise ValueError('source overlaps deployment namespace')
    skills = source_skills(src, source_profile or profile)
    if legacy:
        # 轉換前後的兩種版面都要涵蓋：v1 的 skill 在 dot_claude/skills，v2 的在共用目錄
        skills = skill_names(set(skills) | set(legacy_skills(src)))
    files, targets = mapping(profile, skills)
    if source_profile:
        files = mapping(source_profile, skills)[0]
    paths = [(src, p) for p in set(files) | (set(legacy_files(skills)) if legacy else set())]
    paths += [(dst, p) for p in targets]
    for root, relative in paths:
        rel = Path(relative)
        if rel.is_absolute() or '..' in rel.parts or str(rel) == '.':
            raise ValueError('invalid mapping')
        path = root / rel
        for part in (path, *path.parents):
            if part == root:
                break
            if is_redirected(part):
                raise ValueError('managed symlink')
            if part.exists():
                info = part.stat()
                if part != path and not stat.S_ISDIR(info.st_mode):
                    raise ValueError('invalid managed parent')
                if part == path and (not stat.S_ISREG(info.st_mode) or info.st_nlink != 1):
                    raise ValueError('invalid managed file')
    # Git reads are a separate, explicit metadata scope. Reject indirection here
    # too, so shell status cannot follow metadata links that writes would refuse.
    git_dir = src / '.git'
    if is_redirected(git_dir) or not git_dir.is_dir():
        raise ValueError('regular Git checkout required')
    def walk_error(error):
        raise error
    for parent, dirs, files in os.walk(git_dir, onerror=walk_error):
        if any(is_redirected(Path(parent) / name) for name in dirs + files):
            raise ValueError('Git metadata symlink')
    # A regular file can redirect object reads too; do not follow alternate
    # object stores or another Git directory in any entrypoint, including status.
    for name in ('commondir', 'objects/info/alternates'):
        if (git_dir / name).exists():
            raise ValueError('Git metadata indirection')
    return src, dst


class ScanError(Exception):
    pass


def require(condition):
    if not condition:
        raise ScanError()


def rules():
    data = json.loads(Path(__file__).with_name("gitleaks-rules.json").read_text())
    require(data["version"] == VERSION)
    return frozenset(data["rules"])


def read_json(path):
    require(path.is_file() and not is_redirected(path) and path.stat().st_size <= MAX_BYTES)
    # Reject duplicate JSON keys as well as malformed/truncated reports.
    def pairs(items):
        result = {}
        for key, value in items:
            require(key not in result)
            result[key] = value
        return result
    return json.loads(path.read_text(encoding="utf-8"), object_pairs_hook=pairs)


def validate_report(report, code):
    require(type(report) is dict and set(report) == {"schema", "status", "findings"})
    require(type(report["schema"]) is int and report["schema"] == 1)
    expected = {0: "clean", 10: "secret", 69: "missing", 70: "error"}
    require(code in expected and report["status"] == expected[code])
    findings = report["findings"]
    require(type(findings) is list and len(findings) <= 10000)
    require(bool(findings) == (code == 10))
    allowed_rules = rules()
    for finding in findings:
        require(type(finding) is dict and set(finding) == {"file", "rule", "line"})
        require(admitted(finding["file"]) and finding["rule"] in allowed_rules)
        require(type(finding["line"]) is int and 0 < finding["line"] <= MAX_BYTES)
    return findings


def write_report(path, status, findings):
    # Caller supplies a fresh report path outside the snapshot. Never overwrite.
    with path.open("x", encoding="utf-8") as output:
        json.dump({"schema": 1, "status": status, "findings": findings}, output)
        output.write("\n")


def scan(snapshot):
    require(snapshot.is_absolute() and snapshot.is_dir() and not is_redirected(snapshot))
    binary = shutil.which("gitleaks")
    if not binary:
        return 69, []
    binary = str(Path(binary).resolve())
    with tempfile.TemporaryDirectory(prefix="ai-agent-gitleaks-", dir=str(temporary_root())) as tmp:
        make_private(tmp)
        root = Path(tmp)
        (root / "home").mkdir()
        payload = root / "payload"
        payload.mkdir()
        child_env = dict(child_environment(root / "home"), XDG_CONFIG_HOME=str(root / "home"), TMPDIR=tmp)
        version = subprocess.run([binary, "version"], cwd=tmp, env=child_env,
                                 capture_output=True, timeout=10)
        require(version.returncode == 0 and not version.stderr)
        require(version.stdout.strip() == VERSION.encode("ascii"))
        mapping = {}
        for parent, dirs, files in os.walk(snapshot, followlinks=False, onerror=lambda _: require(False)):
            for name in dirs:
                require(not is_redirected(Path(parent) / name))
            for name in sorted(files):
                original = Path(parent) / name
                location = original.relative_to(snapshot).as_posix()
                require(admitted(location))
                mode = original.lstat().st_mode
                require(stat.S_ISREG(mode) and mode & 0o444)
                require(original.stat().st_size <= MAX_BYTES)
                with original.open("rb") as input_file:
                    content = input_file.read(MAX_BYTES + 1)
                require(len(content) <= MAX_BYTES and b"\x00" not in content)
                content.decode("utf-8", errors="strict")
                # Neutral filenames avoid Gitleaks' default path allowlists and
                # prevent input-controlled paths/config/ignore files affecting it.
                safe_name = "%04d.txt" % len(mapping)
                (payload / safe_name).write_bytes(content)
                mapping[safe_name] = location
        require(mapping)
        config = root / "gitleaks.toml"
        config.write_text("[extend]\nuseDefault = true\n", encoding="utf-8")
        ignore = root / "empty.ignore"
        ignore.write_text("", encoding="utf-8")
        raw_report = root / "report.json"
        result = subprocess.run([
            binary, "dir", str(payload), "--config", str(config),
            "--gitleaks-ignore-path", str(ignore), "--ignore-gitleaks-allow",
            "--exit-code", "10", "--redact=100", "--no-banner", "--no-color",
            "--log-level", "error", "--report-format", "json", "--report-path", str(raw_report),
            "--max-target-megabytes", "0", "--max-decode-depth", "5",
            "--max-archive-depth", "0", "--timeout", "90",
        ], cwd=tmp, env=child_env, capture_output=True, timeout=100)
        require(result.returncode in (0, 10) and not result.stdout and not result.stderr)
        raw = read_json(raw_report)
        require(type(raw) is list and bool(raw) == (result.returncode == 10))
        require(len(raw) <= 10000)
        known_rules = rules()
        findings = set()
        for item in raw:
            require(type(item) is dict)
            rule = item["RuleID"]
            require(rule in known_rules)
            file = Path(item["File"])
            if not file.is_absolute():
                file = root / file
            require(file.parent == payload and file.name in mapping)
            line = item["StartLine"]
            require(type(line) is int and 0 < line <= MAX_BYTES)
            # Never copy Match, Secret, Description, Fingerprint, Commit, etc.
            findings.add((mapping[file.name], rule, line))
        return result.returncode, [dict(file=f, rule=r, line=l) for f, r, l in sorted(findings)]


def main():
    os.umask(0o077)
    if len(sys.argv) in (5, 6) and sys.argv[1] == '--validate-layout':
        try:
            validate_layout(sys.argv[2], sys.argv[3], sys.argv[4], source_profile=sys.argv[5] if len(sys.argv) == 6 else None)
        except (ValueError, OSError):
            return 65
        return 0
    if len(sys.argv) == 4 and sys.argv[1] == '--config':
        # 供 shell 入口讀取單一欄位；無此欄位輸出空字串，無效檔案回傳 78。
        try:
            doc = load_config(sys.argv[2])
        except (ValueError, OSError, ScanError):
            return 78
        value = doc.get(sys.argv[3])
        if value is not None:
            print('true' if value is True else 'false' if value is False else ','.join(value) if type(value) is list else value)
        return 0
    if len(sys.argv) in (4, 5) and sys.argv[1] in ('--schema', '--retired'):
        # 給了 source 根目錄就用它自己的 skill 集合。--retired 從 stdin 讀 HEAD 的路徑，
        # 只列出 HEAD 有、工作目錄已經沒有的 skill 的路徑。
        require(sys.argv[3] in ('source', 'target'))
        try:
            skills = source_skills(sys.argv[4], sys.argv[2]) if len(sys.argv) == 5 else SKILLS
            if sys.argv[1] == '--retired':
                require(len(sys.argv) == 5)
                head = skills_in(sys.stdin.read().splitlines(), sys.argv[2])
                skills = tuple(s for s in head if s not in skills)
            paths = mapping(sys.argv[2], skills)[sys.argv[3] == 'target']
        except (ValueError, OSError):
            return 65
        if sys.argv[1] == '--retired':
            paths = [p for p in paths if skill_of(p)]
        if paths:
            print('\n'.join(paths))
        return 0
    if len(sys.argv) == 3 and sys.argv[1] == '--make-private':
        # 上線用：把參數檔或 plan_dir 設成只有自己能存取（#15 W5）；路徑要存在、絕對、不是重導向
        target = Path(sys.argv[2])
        require(target.is_absolute() and not is_redirected(target) and target.exists())
        try:
            protect(target)
        except OSError:
            print('FAIL: ' + str(target) + ' could not be made private; check its owner and ACL')
            return 70
        print('OK: ' + str(target) + ' is private')
        return 0
    if len(sys.argv) == 3 and sys.argv[1] == '--validate-shared':
        decode_shared(Path(sys.argv[2]).read_bytes())
        return 0
    if len(sys.argv) == 3 and sys.argv[1] == '--wrapper':
        sys.stdout.buffer.write(wrapper(sys.argv[2]))
        return 0
    if len(sys.argv) == 4 and sys.argv[1] == "--display-report":
        # Validate the entire document before emitting even the first finding.
        findings = validate_report(read_json(Path(sys.argv[2])), int(sys.argv[3]))
        for item in findings:
            print("FINDING: %s:%d rule=%s" % (item["file"], item["line"], item["rule"]))
        return 0
    require(len(sys.argv) == 3)
    snapshot, output = map(Path, sys.argv[1:])
    require(output.is_absolute() and not output.exists() and not is_redirected(output))
    require(snapshot.resolve() not in output.resolve().parents)
    try:
        code, findings = scan(snapshot)
    except (OSError, ValueError, KeyError, TypeError, RecursionError, ScanError, subprocess.SubprocessError):
        code, findings = 70, []
    write_report(output, {0: "clean", 10: "secret", 69: "missing", 70: "error"}[code], findings)
    return code


if __name__ == "__main__":
    def interrupted(_signum, _frame):
        # Unwind subprocess.run/TemporaryDirectory on normal termination.
        # SIGKILL cannot be handled; snapshots have owner-only permissions.
        raise KeyboardInterrupt()
    # SIGHUP 在部分平台（例如原生 Windows 的 Python）不存在；缺少時只處理 SIGTERM
    for sig in (signal.SIGTERM, getattr(signal, 'SIGHUP', None)):
        if sig is not None:
            signal.signal(sig, interrupted)
    try:
        sys.exit(main())
    except (OSError, ValueError, KeyError, TypeError, RecursionError, ScanError, subprocess.SubprocessError, KeyboardInterrupt):
        # Exception messages may contain user bytes: never print them or tracebacks.
        sys.exit(70)

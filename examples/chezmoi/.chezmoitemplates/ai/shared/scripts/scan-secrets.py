def temporary_root():
    """引擎所有暫存狀態的固定根目錄：POSIX 是 /tmp；Windows 是使用者的暫存目錄（%TEMP%）。"""
    return Path(tempfile.gettempdir()) if WINDOWS else Path('/tmp')


def is_redirected(path):
    """路徑本身是不是重導向：POSIX 是 symlink；Windows 是任何 reparse point（symlink、junction、
    mount point 等，#39）。路徑不存在回 False，與 is_symlink 相同。"""
    if not WINDOWS:
        return Path(path).is_symlink()
    try:
        info = os.lstat(path)
    except (FileNotFoundError, NotADirectoryError):
        return False
    return bool(info.st_file_attributes & stat.FILE_ATTRIBUTE_REPARSE_POINT)


def scratch_conflict(src, dst, scratch):
    """選定的根目錄不得等於或包含引擎的暫存根。POSIX 看 source 與 destination（例如 HOME=/tmp）。
    Windows：%TEMP% 必然在使用者目錄下，改看 source 與每個部署區；暫存根底下的 source（像 POSIX 的
    /tmp/src）照樣允許，暫存目錄本身由 make_private 保護。"""
    roots = (src, *(dst / region for region in TARGET_REGIONS)) if WINDOWS else (src, dst)
    return any(root == scratch or root in scratch.parents for root in roots)


def absolute_path(value):
    """參數檔裡的路徑格式：POSIX 要求 / 開頭；Windows 要求含磁碟機的絕對路徑。"""
    if WINDOWS:
        return ntpath.isabs(value) and bool(ntpath.splitdrive(value)[0])
    return value.startswith('/')


# Windows 的 ACL（#38）：POSIX 600／700 的等價是「owner 是目前使用者，而且 DACL 只允許使用者、SYSTEM、
# Administrators（以及代表擁有者的 OWNER RIGHTS）」。讀取用 ctypes 取 SDDL，判定是純函式；設定用 icacls，
# 以 SID 寫法、只看 exit code，不解析在地化的輸出。
ACL_ALIASES = {'SY': 'S-1-5-18', 'BA': 'S-1-5-32-544', 'OW': 'S-1-3-4'}
ACL_TRUSTED = ('S-1-5-18', 'S-1-5-32-544', 'S-1-3-4')
# SDDL 的權限代碼（檔案與通用權限；registry 的 KA/KR/KW/KX 只為了解析不失敗）
ACL_RIGHTS = dict(GA=0x10000000, GR=0x80000000, GW=0x40000000, GX=0x20000000, RC=0x20000, SD=0x10000,
                  WD=0x40000, WO=0x80000, FA=0x1F01FF, FR=0x120089, FW=0x120116, FX=0x1200A0,
                  KA=0xF003F, KR=0x20019, KW=0x20006, KX=0x20019,
                  CC=0x1, DC=0x2, LC=0x4, SW=0x8, RP=0x10, WP=0x20, DT=0x40, LO=0x80, CR=0x100)
# 寫入類權限：FILE_WRITE_DATA、FILE_APPEND_DATA、FILE_WRITE_EA、FILE_WRITE_ATTRIBUTES、DELETE、
# WRITE_DAC、WRITE_OWNER、GENERIC_WRITE、GENERIC_ALL
ACL_WRITE = 0x2 | 0x4 | 0x10 | 0x100 | 0x10000 | 0x40000 | 0x80000 | 0x40000000 | 0x10000000
ACL_ALLOW = ('A', 'XA')


def parse_sddl(text):
    """SDDL 字串 → (owner SID, [(ACE 類型, 旗標, 權限遮罩, SID)])。只看 O: 與 D: 區段；別名翻成 SID，
    未知別名原樣保留（之後一律視為其他主體）。格式不對就 ValueError。"""
    owner = re.search(r'O:(S-[0-9-]+|[A-Z]{2})', text)
    dacl = re.search(r'D:[A-Z]*((?:\([^)]*\))*)', text)
    if not owner or not dacl:
        raise ValueError('sddl')
    aces = []
    for ace in re.findall(r'\(([^)]*)\)', dacl.group(1)):
        fields = ace.split(';')
        if len(fields) < 6:
            raise ValueError('sddl ace')
        rights = fields[2]
        if rights.startswith('0x'):
            mask = int(rights, 16)
        else:
            if len(rights) % 2 or any(rights[i:i + 2] not in ACL_RIGHTS for i in range(0, len(rights), 2)):
                raise ValueError('sddl rights')
            mask = 0
            for i in range(0, len(rights), 2):
                mask |= ACL_RIGHTS[rights[i:i + 2]]
        aces.append((fields[0], fields[1], mask, ACL_ALIASES.get(fields[5], fields[5])))
    return ACL_ALIASES.get(owner.group(1), owner.group(1)), aces


def domain_alias(sid, user):
    """SDDL 的網域相對別名：LA 是本機 Administrator 帳號（RID 500）、LG 是 Guest（501），只有展開成
    目前使用者網域下的 SID 才能和使用者比對（CI runner 就是以 Administrator 帳號執行）。"""
    domain = user.rsplit('-', 1)[0]
    return {'LA': domain + '-500', 'LG': domain + '-501'}.get(sid, sid)


def acl_private(descriptor, user, owner=None):
    """owner 是使用者，或是這個程序建立新物件時會指定的 owner（提升權限的 Administrator 建立的檔案由
    Administrators 群組擁有，例如 CI runner）；而且每個 allow ACE 的主體都是使用者、SYSTEM、Administrators
    或 OWNER RIGHTS。deny ACE 只會限制，不影響判定。"""
    actual, aces = descriptor
    return (domain_alias(actual, user) in (user, owner or user)
            and all(kind not in ACL_ALLOW or domain_alias(sid, user) in (user,) + ACL_TRUSTED
                    for kind, _, _, sid in aces))


def acl_foreign_writable(descriptor, user):
    """使用者、SYSTEM、Administrators、OWNER RIGHTS 以外的主體持有寫入類權限；POSIX 的 group/other 可寫。"""
    return any(kind in ACL_ALLOW and domain_alias(sid, user) not in (user,) + ACL_TRUSTED and mask & ACL_WRITE
               for kind, _, mask, sid in descriptor[1])


def windows_api():
    import ctypes
    import ctypes.wintypes as wt
    advapi32 = ctypes.WinDLL('advapi32', use_last_error=True)
    kernel32 = ctypes.WinDLL('kernel32', use_last_error=True)
    kernel32.GetCurrentProcess.restype = wt.HANDLE
    kernel32.LocalFree.argtypes = [wt.HLOCAL]
    kernel32.CloseHandle.argtypes = [wt.HANDLE]
    advapi32.OpenProcessToken.argtypes = [wt.HANDLE, wt.DWORD, ctypes.POINTER(wt.HANDLE)]
    advapi32.GetTokenInformation.argtypes = [wt.HANDLE, ctypes.c_int, ctypes.c_void_p, wt.DWORD, ctypes.POINTER(wt.DWORD)]
    advapi32.ConvertSidToStringSidW.argtypes = [ctypes.c_void_p, ctypes.POINTER(wt.LPWSTR)]
    advapi32.GetFileSecurityW.argtypes = [wt.LPCWSTR, wt.DWORD, ctypes.c_void_p, wt.DWORD, ctypes.POINTER(wt.DWORD)]
    advapi32.ConvertSecurityDescriptorToStringSecurityDescriptorW.argtypes = [
        ctypes.c_void_p, wt.DWORD, wt.DWORD, ctypes.POINTER(wt.LPWSTR), ctypes.POINTER(wt.ULONG)]
    return ctypes, wt, advapi32, kernel32


def security_descriptor(path):
    """以 ctypes 讀取檔案或目錄的 owner 與 DACL；只在 Windows 呼叫。失敗是 OSError。"""
    ctypes, wt, advapi32, kernel32 = windows_api()
    flags = 0x1 | 0x4  # OWNER_SECURITY_INFORMATION | DACL_SECURITY_INFORMATION
    needed = wt.DWORD(0)
    advapi32.GetFileSecurityW(str(path), flags, None, 0, ctypes.byref(needed))
    buffer = ctypes.create_string_buffer(needed.value)
    if not advapi32.GetFileSecurityW(str(path), flags, buffer, needed, ctypes.byref(needed)):
        raise ctypes.WinError(ctypes.get_last_error())
    text = wt.LPWSTR()
    if not advapi32.ConvertSecurityDescriptorToStringSecurityDescriptorW(buffer, 1, flags, ctypes.byref(text), None):
        raise ctypes.WinError(ctypes.get_last_error())
    try:
        return parse_sddl(text.value)
    finally:
        kernel32.LocalFree(text)


USER_SID = None
OWNER_SID = None


def token_sid(kind):
    """目前程序 token 的 SID：kind 1 是 TokenUser（使用者），4 是 TokenOwner（新物件的預設 owner）。"""
    ctypes, wt, advapi32, kernel32 = windows_api()
    token = wt.HANDLE()
    if not advapi32.OpenProcessToken(kernel32.GetCurrentProcess(), 0x8, ctypes.byref(token)):  # TOKEN_QUERY
        raise ctypes.WinError(ctypes.get_last_error())
    try:
        needed = wt.DWORD(0)
        advapi32.GetTokenInformation(token, kind, None, 0, ctypes.byref(needed))
        buffer = ctypes.create_string_buffer(needed.value)
        if not advapi32.GetTokenInformation(token, kind, buffer, needed, ctypes.byref(needed)):
            raise ctypes.WinError(ctypes.get_last_error())
        # TOKEN_USER 與 TOKEN_OWNER 的第一個欄位都是 PSID
        sid = ctypes.cast(buffer, ctypes.POINTER(ctypes.c_void_p))[0]
        text = wt.LPWSTR()
        if not advapi32.ConvertSidToStringSidW(sid, ctypes.byref(text)):
            raise ctypes.WinError(ctypes.get_last_error())
        try:
            return text.value
        finally:
            kernel32.LocalFree(text)
    finally:
        kernel32.CloseHandle(token)


def current_user_sid():
    """目前使用者的 SID；只在 Windows 呼叫，結果快取。"""
    global USER_SID
    if not USER_SID:
        USER_SID = token_sid(1)
    return USER_SID


def token_owner_sid():
    """這個程序建立新檔案時會指定的 owner SID：一般是使用者，提升權限時是 Administrators。"""
    global OWNER_SID
    if not OWNER_SID:
        OWNER_SID = token_sid(4)
    return OWNER_SID


def private_file(path, info):
    """擁有者是自己，而且 group／other 不可寫；Windows 看 owner 與 DACL。"""
    if WINDOWS:
        return acl_private(security_descriptor(path), current_user_sid(), token_owner_sid())
    return info.st_uid == os.getuid() and not info.st_mode & 0o022


def private_mode(path, mode):
    """只有擁有者能存取（plan 檔、manifest）；Windows 看 owner 與 DACL。"""
    if WINDOWS:
        return acl_private(security_descriptor(path), current_user_sid(), token_owner_sid())
    return mode & 0o077 == 0


def foreign_writable(path, info):
    """比標準 644／755 寬鬆：POSIX 是 group 或 other 可寫；Windows 是其他主體持有寫入類權限。"""
    if WINDOWS:
        return acl_foreign_writable(security_descriptor(path), current_user_sid())
    return bool(stat.S_IMODE(info.st_mode) & 0o022)


def private_grants(path):
    """icacls 的授權參數：使用者、SYSTEM、Administrators 各 Full；目錄加上讓子項繼承的旗標。"""
    inherit = '(OI)(CI)' if os.path.isdir(path) else ''
    return ['*%s:%sF' % (sid, inherit) for sid in (current_user_sid(),) + ACL_TRUSTED[:2]]


def private_hint(path):
    """使用者自己要把一個檔案或目錄設成私有時的指令（doctor 與文件用）。"""
    if WINDOWS:
        return 'icacls "%s" /inheritance:r /grant:r %s' % (path, ' '.join(private_grants(path)))
    return 'chmod %s %s' % ('700' if os.path.isdir(path) else '600', path)


def make_private(path):
    """引擎自己建立的私有檔案或目錄。POSIX 已由 mode 參數與 umask 077 決定，不做事；Windows 移除繼承、
    只授權使用者、SYSTEM、Administrators，然後讀回確認。"""
    if not WINDOWS:
        return
    # /reset 先丟掉明確的 ACE（例如使用者自己加的 Everyone），/inheritance:r 再移除繼承的，最後只授權三個主體
    for arguments in (['/reset'], ['/inheritance:r', '/grant:r', *private_grants(path)]):
        run = subprocess.run(['icacls', str(path), *arguments], stdin=subprocess.DEVNULL,
                             stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL, timeout=60)
        if run.returncode != 0:
            raise OSError('icacls failed: ' + str(path))
    descriptor = security_descriptor(path)
    if not acl_private(descriptor, current_user_sid(), token_owner_sid()):
        # 只含 SID 與權限遮罩，沒有檔案內容；CI 等看不到桌面的環境靠這行判斷原因
        raise OSError('private acl not applied: %s owner=%s aces=%s user=%s token_owner=%s'
                      % (path, descriptor[0], descriptor[1], current_user_sid(), token_owner_sid()))


def protect(path):
    """上線時把參數檔或 plan_dir 設成只有自己能存取：POSIX 用 chmod 600／700，Windows 用 ACL。"""
    if WINDOWS:
        make_private(path)
    else:
        os.chmod(path, 0o700 if os.path.isdir(path) else 0o600)


def private_directory_report(path):
    """doctor 的 plan_dir 檢查：(通過, 說明, 修正)。POSIX 要求正好 700。"""
    if WINDOWS:
        ok = acl_private(security_descriptor(path), current_user_sid(), token_owner_sid())
        return ok, ' acl private' if ok else ' acl open to other principals', '' if ok else private_hint(path)
    mode = stat.S_IMODE(os.stat(path).st_mode)
    return mode == 0o700, ' mode %o' % mode, '' if mode == 0o700 else 'chmod 700 ' + str(path)


def set_mode(fd, mode):
    """寫入時設定檔案模式。Windows 沒有 mode bits（os.fchmod 要 3.13 才有），私有檔案由 make_private 的
    ACL 處理，這裡不做事。"""
    if not WINDOWS:
        os.fchmod(fd, mode)


def open_directory(path):
    """取得目錄的檔案描述子供 fsync 用；Windows 沒有目錄 fsync，回傳 None。"""
    return None if WINDOWS else os.open(path, os.O_RDONLY | os.O_DIRECTORY)


def replace(source, target):
    """原子取代。Windows 上目標被其他程式短暫開著（防毒、正在讀取的 agent）會得到 PermissionError：
    有限次重試，仍失敗就照常拋出。"""
    if not WINDOWS:
        os.replace(source, target)
        return
    for attempt in range(5):
        try:
            os.replace(source, target)
            return
        except PermissionError:
            if attempt == 4:
                raise
            time.sleep(0.2 * (attempt + 1))


def child_environment(home, path=None):
    """子程序的最小環境：只有 PATH、HOME 與 C locale。Windows 的 git 與 chezmoi 還需要系統目錄、
    PATHEXT、暫存目錄與 COMSPEC；USERPROFILE 也指到隔離的 home，不讓它們讀到使用者的設定。"""
    env = {'PATH': os.defpath if path is None else path, 'HOME': str(home), 'LC_ALL': 'C'}
    if WINDOWS:
        for key in ('SystemRoot', 'SystemDrive', 'PATHEXT', 'TEMP', 'TMP', 'COMSPEC'):
            if os.environ.get(key):
                env[key] = os.environ[key]
        env['USERPROFILE'] = str(home)
    return env


def scanner_command(path):
    """scanner 以執行檔身分呼叫；Windows 沒有 shebang，交給目前的 Python 直譯器。"""
    return [sys.executable, str(path)] if WINDOWS else [str(path)]


def observed_mode(info, expected):
    """快照記錄的檔案模式。POSIX 是 stat 的 mode bits；Windows 沒有 mode bits，記錄預期值（source 檔是
    HEAD 的模式、target 是 mapping 的標準模式、其他 644）：執行位元由 git 承擔、寬鬆權限由 ACL 承擔。"""
    return expected if WINDOWS else stat.S_IMODE(info.st_mode)


def executable_bit(path, index_mode):
    """status 判斷工作目錄檔案的執行位元：POSIX 看檔案系統；Windows 以 index 為準（沒有 entry 就是 644）。"""
    if WINDOWS:
        return index_mode == '100755'
    return os.access(path, os.X_OK)


def target_executable(path):
    """部署的腳本要可執行；Windows 沒有執行位元，腳本經由 sh 與 python 執行，條件永遠成立。"""
    return True if WINDOWS else os.access(path, os.X_OK)


def target_mode(rel):
    """部署檔的標準模式：引擎腳本與相容入口 755，其餘 644；與 render 的規則相同。"""
    if rel.startswith('.config/ai-agent/bin/'):
        return 0o644 if rel.endswith('.json') else 0o755
    return 0o755 if rel == '.claude/skills/dotfiles-sync/sync.sh' else 0o644


def target_modes(paths):
    return {p: target_mode(p) for p in paths}


def umask_applies():
    """chezmoi 的 umask 設定只在有 mode bits 的平台有意義。"""
    return not WINDOWS


def config_refused(path, label, reason=''):
    """參數檔不被接受時的標籤；Windows 補上原因與把它設成私有的指令。"""
    if not WINDOWS:
        return label
    return label + ('; ' + reason if reason else '') + '; ' + private_hint(path)


def skill_names(names):
    """One closed, ordered set: validated names, the engine's own skill first, the rest sorted."""
    names = set(names) | {SKILLS[0]}
    if len(names) > SKILL_LIMIT or not all(re.fullmatch('[a-z0-9][a-z0-9-]{0,63}', n) for n in names):
        raise ValueError('skill name')
    return (SKILLS[0],) + tuple(sorted(names - {SKILLS[0]}))


def skill_of(path, kinds=SKILL_SOURCES + SKILL_TARGETS + SKILL_LEGACY):
    """Directory name of the skill a per-skill path belongs to, or None. The name is not validated."""
    for prefix, suffix in kinds:
        if path.startswith(prefix) and path.endswith(suffix):
            name = path[len(prefix):len(path) - len(suffix)]
            if name and '/' not in name:
                return name
    return None


def skills_in(paths, profile='claude-codex'):
    """Skill set of one source snapshot, from its own paths (a Git tree or a working tree listing).

    A skill is a directory with a SKILL.md under the shared skill root. Every other
    path there stays out of scope. A wrapper without its skill would break a real
    chezmoi render, so it is refused instead of ignored.
    """
    if profile not in PROFILES:
        raise ValueError('invalid profile')
    paths = set(paths)
    names = skill_names(filter(None, (skill_of(p, SKILL_SOURCES[:1]) for p in paths)))
    wrappers = [kind for kind, product in zip(SKILL_SOURCES[1:], ('claude', 'codex')) if product in profile]
    if any(skill_of(p, wrappers) not in names + (None,) for p in paths):
        raise ValueError('wrapper without skill')
    return names


def source_skills(source, profile='claude-codex'):
    """Skill set of the working tree. Lists three fixed source directories, never the destination."""
    root = Path(source)
    paths = []
    for prefix, suffix in SKILL_SOURCES:
        directory = root / prefix
        if any(is_redirected(part) for part in (directory, *directory.parents) if part != root and root in part.parents):
            raise ValueError('managed symlink')
        if not directory.is_dir():
            if prefix == SKILL_ROOT:
                return SKILLS
            continue
        entries = os.listdir(directory)
        if len(entries) > 4096:
            raise ValueError('skill directory')
        paths += [prefix + name + suffix for name in entries if os.path.lexists(str(directory / name) + suffix)]
    return skills_in(paths, profile)


def legacy_skills(source):
    """Skill set of a v1 source: every directory with a SKILL.md under dot_claude/skills."""
    root = Path(source)
    directory = root / 'dot_claude/skills'
    if any(is_redirected(part) for part in (directory, *directory.parents) if part != root and root in part.parents):
        raise ValueError('managed symlink')
    if not directory.is_dir():
        return skill_names(())
    entries = os.listdir(directory)
    if len(entries) > 4096:
        raise ValueError('skill directory')
    return skill_names(name for name in entries if os.path.lexists(directory / name / 'SKILL.md'))


